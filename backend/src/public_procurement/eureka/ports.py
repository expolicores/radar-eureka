import uuid
from collections.abc import Callable, Iterable
from contextlib import AbstractContextManager
from datetime import datetime
from typing import Any, Protocol

from .domain.details import CanonicalInput, StoredOpportunity
from .domain.discovery import ProcessFacts


class ProcessMetadataSource(Protocol):
    def iter_processes(
        self, reference: str | None, department: str | None
    ) -> Iterable[ProcessFacts]: ...


class CanonicalFactsSource(Protocol):
    def read(self, reference: str) -> CanonicalInput: ...

    def evidence(self, reference: str, canonical_id: uuid.UUID) -> list[dict[str, Any]]: ...


class OpportunityQueries(Protocol):
    def get_by_process(self, process_id: uuid.UUID) -> StoredOpportunity | None: ...

    def get_by_id(self, opportunity_id: uuid.UUID) -> StoredOpportunity | None: ...

    def all(self) -> list[StoredOpportunity]: ...


class RadarRepository(Protocol):
    def lock(self) -> AbstractContextManager[None]: ...
    def start(self, run: dict[str, Any], snapshot: dict[str, Any]) -> None: ...
    def state(self, dataset: str, secop_id: str) -> dict[str, Any] | None: ...
    def claim(self, run_id: uuid.UUID, dataset: str, secop_id: str, at: datetime) -> None: ...
    def stage(self, dataset: str, secop_id: str, stage: str, at: datetime) -> None: ...
    def outcome(
        self, run_id: uuid.UUID, item: dict[str, Any], at: datetime, update_state: bool
    ) -> None: ...
    def finish(self, run: dict[str, Any]) -> None: ...
    def alert(
        self,
        run_id: uuid.UUID,
        opportunity_id: uuid.UUID,
        version: str,
        decision: Any,
        at: datetime,
    ) -> bool: ...


class RadarPipeline(Protocol):
    def enrich(self, process: Any, stage: Callable[[str], None]) -> Any: ...
    def preview(self, reference: str) -> Any: ...
    def evidence(self, reference: str, canonical_id: uuid.UUID) -> list[dict[str, Any]]: ...
